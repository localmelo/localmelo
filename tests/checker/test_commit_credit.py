"""A commit made from a step does not credit melo or an AI.

``Checker.pre_execute`` refuses a ``shell_exec`` or ``python_exec`` call that
makes a git commit with a line that names melo or an AI: a ``Co-Authored-By``
trailer, a ``Generated with`` line, a session link. A trailer that names a
person, and a call that is no commit, are left alone.
"""

from __future__ import annotations

import pytest

from localmelo.melo.checker import Checker
from localmelo.melo.checker.commits import commit_credit_refusal
from localmelo.melo.contracts.approvals import ApprovalDecision
from localmelo.melo.executor import (
    ErrorCategory,
    ExecutionRequest,
    ExecutionStatus,
    Executor,
    register_builtins,
)
from localmelo.melo.memory.coordinator import Hippo
from localmelo.melo.schema import ToolCall, ToolDef

CREDITED = [
    'git commit -m "Fix it" -m "Co-Authored-By: melo <melo@localmelo.dev>"',
    'git commit -m "Fix it\n\nCo-Authored-By: Claude <noreply@anthropic.com>"',
    "git commit -m 'Fix it' -m 'co-authored-by: ChatGPT <bot@openai.com>'",
    "git commit -m 'Fix it' -m 'Co-Authored-By: GPT-5 <x@example.com>'",
    'git commit -m "Fix it" -m "Generated with [Claude Code](https://claude.com)"',
    'git commit -m "Fix it" -m "Generated by localmelo"',
    'git commit -m "Fix it" -m "Claude-Session: https://claude.ai/code/session_01"',
    'git -C app commit -m "Fix it https://claude.ai/code/session_01AbC"',
    "git commit -F- <<'EOF'\nFix it\n\nCo-Authored-By: melo <melo@localmelo.dev>\nEOF",
]
CREDITED_PY = [
    'import subprocess\nsubprocess.run(["git", "commit", "-m", "Fix\\n\\n'
    'Co-Authored-By: melo <melo@localmelo.dev>"], check=True)\n',
    "import subprocess\nmsg = 'Fix\\n\\nGenerated with Claude Code'\n"
    "subprocess.run(['git', 'commit', '-m', msg])\n",
]
FINE = [
    'git commit -m "Fix it"',
    'git commit -m "Fix it" -m "Co-Authored-By: Ada Lovelace <ada@example.com>"',
    'git commit -m "Rename claude_helper to helper"',
    'git commit -m "Document the AI features of the app"',
    'git commit -m "Docs: generated with protobuf"',
    'echo "Co-Authored-By: melo <melo@localmelo.dev>" > notes.txt',
    "git log --oneline | grep claude",
    "pytest -q && git status",
]


@pytest.mark.parametrize("command", CREDITED)
def test_a_commit_that_credits_melo_or_an_ai_is_refused(command: str) -> None:
    reason = commit_credit_refusal("shell_exec", {"command": command})

    assert reason is not None
    assert reason.startswith("This commit message credits melo or an AI (")
    assert "Commit again without that line" in reason


@pytest.mark.parametrize("code", CREDITED_PY)
def test_the_same_in_python_code(code: str) -> None:
    assert commit_credit_refusal("python_exec", {"code": code}) is not None


@pytest.mark.parametrize("command", FINE)
def test_a_commit_without_a_credit_and_other_calls_are_left_alone(
    command: str,
) -> None:
    assert commit_credit_refusal("shell_exec", {"command": command}) is None
    assert commit_credit_refusal("python_exec", {"code": command}) is None


def test_only_the_shell_and_python_tools_are_looked_at() -> None:
    text = 'git commit -m "x" -m "Co-Authored-By: melo <melo@localmelo.dev>"'

    assert commit_credit_refusal("file_write", {"content": text}) is None
    assert commit_credit_refusal("shell_exec", {"command": 7}) is None
    assert commit_credit_refusal("shell_exec", {}) is None


async def test_the_checker_blocks_the_call_with_the_reason() -> None:
    tool = ToolDef("shell_exec", "run", {})
    credited = ToolCall(
        tool_name="shell_exec",
        arguments={"command": CREDITED[0]},
    )
    fine = ToolCall(tool_name="shell_exec", arguments={"command": FINE[0]})
    checker = Checker(mode="interactive")

    blocked = await checker.pre_execute(credited, tool)
    allowed = await checker.pre_execute(fine, tool)

    assert not blocked.allowed and "credits melo or an AI" in blocked.reason
    assert allowed.allowed


async def test_a_credited_commit_is_refused_before_anyone_is_asked() -> None:
    hippo = Hippo()
    executor = Executor(hippo, Checker(mode="interactive"))
    register_builtins(executor, hippo, names={"shell_exec"}, mode="interactive")
    asked: list[ExecutionRequest] = []

    async def gate(request: ExecutionRequest) -> ApprovalDecision:
        asked.append(request)
        return ApprovalDecision(True)

    outcome = await executor.execute_structured(
        ExecutionRequest("shell_exec", {"command": CREDITED[0]}), approve=gate
    )

    assert asked == []
    assert outcome.status == ExecutionStatus.BLOCKED
    assert outcome.error_category == ErrorCategory.BLOCKED_BY_CHECKER
    assert outcome.error.startswith("Blocked: This commit message credits melo")
